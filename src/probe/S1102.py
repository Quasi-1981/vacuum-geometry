def sin_active(nu, h):
    """Hand-A (S1005/S1011): time-activity of ν ⟺ sin(2πν/h) ≠ 0 ⟺ ν ∉ {0, h/2}."""
    from sympy import sin, pi, Rational
    return sin(2*pi*Rational(nu, h)) != 0

def step_active(nu, h, clock, Tstep):
    """Hand-B (the step): does the character of ν read ⟨c⟩∩Tstep nontrivially?
    ν is nontrivial on the intersection ⟺ there exists g in (⟨c⟩∩Tstep) with
    e^{2πi ν k(g)/h} ≠ 1, where k(g) = the power of c that gives g.  Returns
    (active, |intersection|)."""
    from sympy import exp, I, pi, Rational, simplify
    c = clock.generators[0]
    # the elements of the intersection ⟨c⟩ ∩ Tstep, with their power k
    inter = []
    cur = Permutation(list(range(clock.degree)))
    for k in range(h):
        if k > 0:
            cur = cur * c
        if Tstep.contains(cur):
            inter.append(k)
    # ν is active ⟺ the character is nontrivial on some nonzero element of the intersection
    active = any(simplify(exp(2*I*pi*Rational(nu*k, h)) - 1) != 0 for k in inter if k != 0)
    return active, len(inter)

