def galois_of(poly_expr):
    """The Galois group of an IRREDUCIBLE polynomial = the permutation group of its roots (a
    construction, not a theorem).  Returns a PermutationGroup or raises if reducible."""
    G, _ = galois_group(Poly(poly_expr, x))
    return G

