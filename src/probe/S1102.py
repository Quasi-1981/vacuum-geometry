def fence_number(poly_expr, name):
    """The fence for an ALGEBRAIC NUMBER given by its defining polynomial.
    Rule (binary, 0 handles): legal <=> the Galois group of the min-polynomial is
    SOLVABLE (the derived series is read down to {e} by our own hand).  If reducible => each
    irreducible factor is judged separately (the number = a root of one of them); legal <=>
    ALL factors are solvable.  Rational/linear => trivially legal (a named degeneration).
    Returns (legal: bool, detail: str)."""
    p = Poly(poly_expr, x, domain=QQ)
    factors = [fp for (fp, m) in p.factor_list()[1]]
    degs = sorted(fp.degree() for fp in factors)
    if all(fp.degree() == 1 for fp in factors):
        return True, f"rational/linear (degrees {degs}) — legal TRIVIALLY (a degeneration)"
    parts = []
    all_solv = True
    for fp in factors:
        if fp.degree() == 1:
            parts.append("lin:solv."); continue
        G = galois_of(fp.as_expr())
        solv = is_solvable_by_hand(G)
        all_solv = all_solv and solv
        parts.append(f"deg{fp.degree()}:|Gal|={G.order()},{'solv.' if solv else 'NOT SOLV.'}")
    return all_solv, "; ".join(parts) + (f"  (degrees of factors {degs})" if len(factors)>1 else "")

